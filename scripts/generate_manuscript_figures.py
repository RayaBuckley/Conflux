#!/usr/bin/env python3
"""Generate the manuscript's figures from retained result bundles.

Inputs (read-only; sha256 recorded in generated/figures/CHECKSUMS.sha256):
  research/output/runs/defence-models-v1/sensitivity.json
  research/output/runs/ic3-unbounded-v1/result.json
  research/output/runs/parameter-general-v1/result.json
  research/output/runs/runpod-h100-14b-v1/result.json
  research/output/runs/runpod-h100-14b-stratified/*/result.json
Outputs:
  research/publications/manuscript/generated/figures/f1_property_sensitivity.tex
  research/publications/manuscript/generated/figures/f2_unbounded_routes.tex
  research/publications/manuscript/generated/figures/f3_runpod_cells.tex

The figures use plain TikZ only (no pgfplots, no patterns library): three grey levels
plus a printed count in every segment, so the encoding is not carried by colour alone.
Deterministic: identical inputs produce byte-identical outputs.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "research" / "output" / "runs"
FIGS = ROOT / "research" / "publications" / "manuscript" / "generated" / "figures"
if "--outdir" in sys.argv:
    _candidate = Path(sys.argv[sys.argv.index("--outdir") + 1])
    FIGS = _candidate if _candidate.is_absolute() else ROOT / _candidate
CHECK = "--check" in sys.argv
PROBLEMS: list[str] = []

FILL = {"checked": "black!75", "checked_by_construction": "black!30", "violated_at_baseline": "white"}
CLASSES = ["checked", "checked_by_construction", "violated_at_baseline"]


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def header(inputs: list[Path], title: str) -> list[str]:
    out = [
        f"% {title}",
        "% Generated by scripts/generate_manuscript_figures.py - do not edit by hand.",
    ]
    for path in inputs:
        out.append(f"% input: {path.relative_to(ROOT).as_posix()} sha256={digest(path)}")
    return out


def write(name: str, lines: list[str], inputs: list[Path], title: str) -> Path:
    target = FIGS / name
    text = "\n".join(header(inputs, title) + lines) + "\n"
    if CHECK:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            PROBLEMS.append(target.relative_to(ROOT).as_posix())
            print(f"[figure-check] stale: {target.relative_to(ROOT).as_posix()}")
        return target
    target.write_text(text, encoding="utf-8")
    print(f"  {target.relative_to(ROOT).as_posix()}  {target.stat().st_size} bytes")
    return target


def legend(y: float, x0: float) -> list[str]:
    out, x = [], x0
    for name in CLASSES:
        label = name.replace("_", "\\_")
        out.append(f"  \\fill[{FILL[name]}] ({x:.2f},{y:.2f}) rectangle +(0.42,0.26);")
        out.append(f"  \\draw[black,line width=0.3pt] ({x:.2f},{y:.2f}) rectangle +(0.42,0.26);")
        out.append(f"  \\node[anchor=west,font=\\scriptsize] at ({x + 0.5:.2f},{y + 0.13:.2f}) {{{label}}};")
        x += 0.55 + 0.042 * len(name)
    return out


def stacked_rows(rows: list[tuple[str, dict[str, int]]], unit: float, top: float) -> list[str]:
    """rows = [(label, {class: count})]; draws left-to-right stacked bars, top row first."""
    out, y = [], top
    for label, counts in rows:
        out.append(f"  \\node[anchor=east,font=\\small] at (-0.15,{y + 0.16:.2f}) {{{label}}};")
        x = 0.0
        for name in CLASSES:
            n = counts.get(name, 0)
            if not n:
                continue
            width = n * unit
            out.append(f"  \\fill[{FILL[name]}] ({x:.2f},{y:.2f}) rectangle +({width:.2f},0.32);")
            out.append(f"  \\draw[black,line width=0.3pt] ({x:.2f},{y:.2f}) rectangle +({width:.2f},0.32);")
            out.append(f"  \\node[font=\\scriptsize] at ({x + width / 2:.2f},{y + 0.16:.2f}) {{{n}}};")
            x += width
        out.append(f"  \\node[anchor=west,font=\\scriptsize] at ({x + 0.08:.2f},{y + 0.16:.2f}) {{{sum(counts.values())}}};")
        y -= 0.55
    return out


def figure_f1() -> Path:
    path = RUNS / "defence-models-v1" / "sensitivity.json"
    data = json.loads(path.read_text())
    groups = {
        "Dual-LLM": ["dual_llm_native_property", "dual_llm_pe"],
        "CaMeL": ["camel_native_property", "camel_pe"],
        "Progent": ["progent_native_property", "progent_pe"],
        "PACT": ["pact_native_property", "pact_pe"],
        "Requester-only": ["ites_requester_only"],
        "ITES": ["ites_native_property", "ites_pe", "ites_with_read_check"],
    }
    rows = []
    for label, ids in groups.items():
        counts = {name: 0 for name in CLASSES}
        for ir_id in ids:
            for inv in data["irs"][ir_id]["invariants"]:
                counts[inv["exercise_class"]] += 1
        rows.append((label, counts))
    lines = ["\\begin{tikzpicture}[x=1cm,y=1cm]"]
    lines += stacked_rows(rows, unit=0.62, top=0.0)
    lines += [
        "  \\draw[black,line width=0.4pt] (0,-3.62) -- (4.6,-3.62);",
        "  \\node[anchor=north west,font=\\scriptsize] at (0,-3.72) {invariant rows (number printed in each segment)};",
    ]
    lines += legend(-4.35, 0.0)
    lines.append("\\end{tikzpicture}")
    return write("f1_property_sensitivity.tex", lines, [path], "Figure 1: property-sensitivity classes")


def figure_f2() -> Path:
    ic3 = RUNS / "ic3-unbounded-v1" / "result.json"
    pg = RUNS / "parameter-general-v1" / "result.json"
    verdicts = json.loads(ic3.read_text())["summary"]["by_verdict"]
    pg_verdicts = json.loads(pg.read_text())["summary"]["by_verdict"]
    order = ["safe", "unsafe", "unknown"]
    fill = {"safe": "white", "unsafe": "black!75", "unknown": "black!30"}
    rows = [("IC3/PDR (689 rows)", {k: verdicts[k] for k in order}, 689),
            ("PredAbs + induction (7 rows)", {k: pg_verdicts[k] for k in order}, 7)]
    lines = ["\\begin{tikzpicture}[x=1cm,y=1cm]"]
    y = 0.0
    for label, counts, total in rows:
        lines.append(f"  \\node[anchor=east,font=\\small,align=right] at (-0.15,{y + 0.16:.2f}) {{{label}}};")
        lines.append(f"  \\fill[black!8] (0,{y:.2f}) rectangle +(9.0,0.32);")
        x = 0.0
        for name in order:
            n = counts[name]
            if not n:
                continue
            width = 9.0 * n / total
            lines.append(f"  \\fill[{fill[name]}] ({x:.2f},{y:.2f}) rectangle +({width:.2f},0.32);")
            lines.append(f"  \\draw[black,line width=0.3pt] ({x:.2f},{y:.2f}) rectangle +({width:.2f},0.32);")
            if width >= 0.75:
                lines.append(f"  \\node[font=\\scriptsize] at ({x + width / 2:.2f},{y + 0.16:.2f}) {{{n}}};")
            x += width
        lines.append(f"  \\node[anchor=north west,font=\\scriptsize] at (0,{y - 0.06:.2f}) {{share of the {total} rows in this bundle}};")
        y -= 1.25
    lines += [
        "  \\draw[black,line width=0.4pt] (0,-2.1) -- (9.0,-2.1);",
        "  \\node[anchor=north west,font=\\scriptsize] at (0,-2.2) {all rows decided by the route, normalised per bundle};",
    ]
    for i, name in enumerate(order):
        x = i * 2.0
        lines.append(f"  \\fill[{fill[name]}] ({x},-2.95) rectangle +(0.42,0.26);")
        lines.append(f"  \\draw[black,line width=0.3pt] ({x},-2.95) rectangle +(0.42,0.26);")
        lines.append(f"  \\node[anchor=west,font=\\scriptsize] at ({x + 0.5:.2f},-2.82) {{{name}}};")
    lines.append("\\end{tikzpicture}")
    return write("f2_unbounded_routes.tex", lines, [ic3, pg], "Figure 2: verdict split per unbounded route")


def figure_f3() -> Path:
    v1 = RUNS / "runpod-h100-14b-v1" / "result.json"
    stratified_paths = sorted((RUNS / "runpod-h100-14b-stratified").glob("*/result.json"))
    rows: list[tuple[str, dict[str, int]]] = []
    cells_v1 = json.loads(v1.read_text())["cells"]
    by_arm: dict[str, list[int]] = {}
    for cell in cells_v1:
        arm_tally = by_arm.setdefault(cell["defence"], [0, 0])
        arm_tally[0 if cell["status"] == "complete" else 1] += 1
    for arm, (ok, bad) in sorted(by_arm.items()):
        rows.append((f"v1, {arm.replace('_', chr(92) + '_')}", {"complete": ok, "failed": bad}))
    for path in stratified_paths:
        bundle = json.loads(path.read_text())
        tally: dict[str, int] = {"complete": 0, "failed": 0}
        for cell in bundle["cells"]:
            tally["complete" if cell["status"] == "complete" else "failed"] += 1
        rows.append((path.parent.name.replace("agentdojo-stratified-", "stratified "), tally))
    fill = {"complete": "black!75", "failed": "white"}
    lines = ["\\begin{tikzpicture}[x=1cm,y=1cm]"]
    y = 0.0
    for label, counts in rows:
        total = sum(counts.values())
        lines.append(f"  \\node[anchor=east,font=\\small] at (-0.15,{y + 0.16:.2f}) {{{label}}};")
        x = 0.0
        for name in ("complete", "failed"):
            n = counts[name]
            if not n:
                continue
            width = 0.30 * n
            lines.append(f"  \\fill[{fill[name]}] ({x:.2f},{y:.2f}) rectangle +({width:.2f},0.32);")
            lines.append(f"  \\draw[black,line width=0.3pt] ({x:.2f},{y:.2f}) rectangle +({width:.2f},0.32);")
            if width >= 0.8:
                lines.append(f"  \\node[font=\\scriptsize] at ({x + width / 2:.2f},{y + 0.16:.2f}) {{{n}}};")
            x += width
        lines.append(f"  \\node[anchor=west,font=\\scriptsize] at ({x + 0.08:.2f},{y + 0.16:.2f}) {{{total} cells}};")
        y -= 0.55
    lines.append(f"  \\draw[black,line width=0.4pt] (0,{y + 0.28:.2f}) -- (8.2,{y + 0.28:.2f});")
    lines.append(f"  \\node[anchor=north west,font=\\scriptsize] at (0,{y + 0.18:.2f}) {{cells by arm (v1) and by stratum (stratified run)}};")
    y -= 0.75
    for i, (name, f) in enumerate((("complete", fill["complete"]), ("failed", fill["failed"]))):
        x = i * 2.2
        lines.append(f"  \\fill[{f}] ({x},{y:.2f}) rectangle +(0.42,0.26);")
        lines.append(f"  \\draw[black,line width=0.3pt] ({x},{y:.2f}) rectangle +(0.42,0.26);")
        lines.append(f"  \\node[anchor=west,font=\\scriptsize] at ({x + 0.5:.2f},{y + 0.13:.2f}) {{{name}}};")
    lines.append("\\end{tikzpicture}")
    return write("f3_runpod_cells.tex", lines, [v1] + stratified_paths, "Figure 3: runpod cells per arm and per stratum")


def main() -> int:
    FIGS.mkdir(parents=True, exist_ok=True)
    written = [figure_f1(), figure_f2(), figure_f3()]
    checks = FIGS / "CHECKSUMS.sha256"
    text = "".join(f"{digest(p)}  {p.name}\n" for p in written)
    if CHECK:
        if not checks.exists() or checks.read_text(encoding="utf-8") != text:
            PROBLEMS.append(checks.relative_to(ROOT).as_posix())
    else:
        checks.write_text(text, encoding="utf-8")
        print(f"  {checks.relative_to(ROOT).as_posix()}  {checks.stat().st_size} bytes")
    if CHECK:
        if PROBLEMS:
            print("[figure-check] figures are stale; re-run without --check")
            return 1
        print("[figure-check] figures current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
